let temperaturaAtual = 10;

if (temperaturaAtual >= 30){
    console.log("A temperatura está quente! Aproximadamente: " + temperaturaAtual + "°C");
} else if (temperaturaAtual >= 20){
    console.log("A temperatura está agradável! Aproximadamente: " + temperaturaAtual + "°C");
} else {
    console.log("A temperatura está fria! Aproximadamente " + temperaturaAtual + "°C");
}