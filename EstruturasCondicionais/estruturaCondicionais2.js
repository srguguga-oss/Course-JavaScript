// Switch

let dia = 6;

switch(dia){
    case 1:
        console.log("Domingo");
        break;
    case 2:
        console.log("Segunda-feira");
        break;
    case 3:
        console.log("Terça-feira");
        break;
    case 4:
        console.log("Quarta-feira");
        break;
    case 5:
        console.log("Quinta-feira");
        break;
    case 6:
        console.log("Sexta-feira");
        break;
    case 7:
        console.log("Sábado");
        break;
    default:
        console.log("Opção inválida!");
}

let cor = "vermelho";

switch(cor){
    case "Vermelho":
        console.log("Pare!");
        break;
    case "Amarelo":
        console.log("Atenção!");
        break;
    case "Verde":
        console.log("Pode passar!");
        break;
    default:
        console.log("Não existe esta cor em semáforo.");
}
